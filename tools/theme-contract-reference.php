<?php

/**
 * Writes docs/reference/theme-contract.md from the theme-interface package, so the page can't drift from the contract.
 *
 * Usage, from the docs folder, with a theme-interface checkout that has its Composer dependencies:
 *     php tools/theme-contract-reference.php ../theme-interface > docs/reference/theme-contract.md
 */

declare(strict_types=1);

use SightPress\Theme\LayoutDefinition;
use SightPress\Theme\Template\RequiredTemplates;
use SightPress\Theme\Template\TemplateApi;
use SightPress\Theme\Token\ChartTokens;
use SightPress\Theme\Token\TokenGroup;

$package = rtrim($argv[1] ?? '../theme-interface', '/');
require $package . '/vendor/autoload.php';

$cell = static fn (string $text): string => str_replace(['|', "\n"], ['\\|', ' '], $text);
$code = static fn (string $text): string => '`' . str_replace('|', '\\|', $text) . '`';
$schema = json_decode((string) file_get_contents($package . '/resources/theme.schema.json'), true, flags: JSON_THROW_ON_ERROR);
$required = $schema['required'] ?? [];
// The schema leaves these groups undescribed.
$described = [
    'colors' => 'The colours for light and dark mode, and optionally for more contrast.',
    'typography' => 'Fonts and text sizes.',
    'spacing' => 'The spacing scale.',
    'radius' => 'Corner radii.',
    'focus' => 'The focus outline.',
];

$out = <<<'MD'
# Theme contract

<!-- Generated by tools/theme-contract-reference.php from theme-interface. Don't edit by hand. -->

This page lists what a SightPress theme can rely on and must provide. It is generated from the `sightpress/theme-interface`
package. To build a theme step by step, follow the [Create a theme](../tutorials/create-a-theme.md) tutorial.

A theme is presentation only: design tokens, Twig templates, assets and translations. Anything with behaviour is a
module.

## theme.json

MD;
$out .= "\n| Key | Required | What it is |\n| --- | --- | --- |\n";
foreach ($schema['properties'] as $key => $property) {
    if ($key === '$schema') {
        continue;
    }
    $out .= sprintf("| %s | %s | %s |\n", $code($key), in_array($key, $required, true) ? 'Yes' : 'No', $cell((string) ($property['description'] ?? $described[$key] ?? '')));
}

$out .= "\n## Token groups\n\nEach group becomes CSS custom properties with this prefix.\n\n| Group | Prefix |\n| --- | --- |\n";
foreach (TokenGroup::cases() as $group) {
    $out .= sprintf("| %s | %s |\n", $code($group->value), $code('--' . $group->cssPrefix() . '-'));
}
$out .= sprintf("\nCharts use the colours %s.\n", implode(', ', array_map($code, ChartTokens::COLORS)));

$out .= "\n## Layouts\n\n| Id | Name | Required | What it is |\n| --- | --- | --- | --- |\n";
$layouts = [];
foreach ([...LayoutDefinition::required(), ...LayoutDefinition::standard()] as $layout) {
    $layouts[$layout->id] = $layout;
}
foreach ($layouts as $layout) {
    $out .= sprintf("| %s | %s | %s | %s |\n", $code($layout->id), $cell($layout->label), $layout->isRequired() ? 'Yes' : 'No', $cell($layout->description));
}

$out .= "\n## Required templates\n";
foreach (RequiredTemplates::all() as $template) {
    $out .= sprintf("\n### %s\n\n%s\n", $template->file, $template->description);
    if ($template->blocks !== []) {
        $out .= sprintf("\nTwig blocks: %s.\n", implode(', ', array_map($code, $template->blocks)));
    }
    if ($template->variables !== []) {
        $out .= "\n| Variable | Type | Required | What it is |\n| --- | --- | --- | --- |\n";
        foreach ($template->variables as $variable) {
            $out .= sprintf("| %s | %s | %s | %s |\n", $code($variable->name), $code($variable->type), $variable->required ? 'Yes' : 'No', $cell($variable->description));
        }
    }
}

$out .= "\n## Twig functions and filters\n\n| Name | Kind | Use | What it does |\n| --- | --- | --- | --- |\n";
foreach (TemplateApi::functions() as $function) {
    $out .= sprintf("| %s | %s | %s | %s |\n", $code($function->name), $function->kind->value, $code($function->signature), $cell($function->description));
}

echo $out;
