<?php

/**
 * Writes docs/reference/module-interface.md from the module-interface package, so the page can't drift from the
 * contract: what a module registers (ModuleRegistrar), every area of the contract with its classes, and the events a
 * module can listen to, with their fields.
 *
 * Usage, from the docs folder, with a module-interface checkout that has its Composer dependencies:
 *     php tools/module-interface-reference.php ../module-interface > docs/reference/module-interface.md
 */

declare(strict_types=1);

$package = rtrim($argv[1] ?? '../module-interface', '/');
require $package . '/vendor/autoload.php';

// The latest release of the checkout, for example 0.5.0.
$version = trim((string) shell_exec('git -C ' . escapeshellarg($package) . ' describe --tags --abbrev=0 2>/dev/null'));
$version = $version === '' ? 'dev' : $version;

/** The first sentence of a docblock, on one line, without tags. */
$summary = static function (string|false $doc): string {
    if ($doc === false) {
        return '';
    }
    $lines = [];
    foreach (preg_split('/\R/', $doc) ?: [] as $line) {
        $line = trim(preg_replace('#^\s*(/\*\*|\*/|\*)#', '', $line) ?? '');
        if (str_starts_with($line, '@')) {
            break;
        }
        $lines[] = $line;
    }
    $text = trim(preg_replace('/\s+/', ' ', implode(' ', $lines)) ?? '');
    $text = preg_replace('/\{@see\s+([^}]+)\}/', '`$1`', $text) ?? $text;
    if (preg_match('/^(.+?[.!?])(\s|$)/u', $text, $match) === 1) {
        return $match[1];
    }

    return $text;
};
$cell = static fn (string $text): string => str_replace(['|', "\n"], ['\\|', ' '], $text);

// Every class, interface and enum of the package, by area (the namespace under SightPress\Module).
$areas = [];
$iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($package . '/src', FilesystemIterator::SKIP_DOTS));
foreach ($iterator as $file) {
    if ($file->getExtension() !== 'php') {
        continue;
    }
    $relative = substr($file->getPathname(), strlen($package . '/src/'), -4);
    $class = 'SightPress\\Module\\' . str_replace('/', '\\', $relative);
    $area = str_contains($relative, '/') ? explode('/', $relative)[0] : 'Module';
    if ($area === 'Internal') {
        continue;
    }
    $areas[$area][] = $class;
}
ksort($areas);
foreach ($areas as &$classes) {
    sort($classes);
}
unset($classes);

$kind = static fn (ReflectionClass $class): string => match (true) {
    $class->isEnum() => 'enum',
    $class->isInterface() => 'interface',
    $class->isAbstract() => 'abstract class',
    default => 'class',
};

$out = <<<MD
# Module interface reference

<!-- Generated by tools/module-interface-reference.php from module-interface. Don't edit by hand. -->

This page lists what a SightPress module can use: the `sightpress/module-interface` package ({$version}). A module
depends on this package only, never on `sightpress/core`. To install one, see [Add a module](../how-to/add-a-module.md).

## What a module registers

A module implements `ModuleInterface`: `manifest()` says who it is, and `register(ModuleRegistrar \$registrar)` adds
what it brings. Each method of the registrar gives one kind of thing:

| Method | What it adds |
| --- | --- |

MD;
$registrar = new ReflectionClass('SightPress\\Module\\ModuleRegistrar');
foreach ($registrar->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
    $text = $summary($method->getDocComment());
    $returns = $method->getReturnType();
    // Without a docblock of its own, a method says what the registrar it returns is for.
    if ($text === '' && $returns instanceof ReflectionNamedType && (class_exists($returns->getName()) || interface_exists($returns->getName()))) {
        $text = $summary(new ReflectionClass($returns->getName())->getDocComment());
    }
    $out .= sprintf("| `%s()` | %s |\n", $method->getName(), $cell($text));
}

$out .= "\n## Events\n\nA module listens to an event with `\$registrar->subscribers()`. Events are in `SightPress\\Module\\Event`; ";
$out .= "values that core keeps as enums travel as strings.\n\n| Event | When | Fields |\n| --- | --- | --- |\n";
foreach ($areas['Event'] ?? [] as $name) {
    $class = new ReflectionClass($name);
    $fields = array_map(static function (ReflectionProperty $property): string {
        $type = $property->getType();

        return sprintf('`%s` (%s)', $property->getName(), $type === null ? 'mixed' : (string) $type);
    }, $class->getProperties(ReflectionProperty::IS_PUBLIC));
    $out .= sprintf("| `%s` | %s | %s |\n", $class->getShortName(), $cell($summary($class->getDocComment())), implode(', ', $fields));
}

$out .= "\n## Every part of the contract\n\nBy area (namespace under `SightPress\\Module`).\n";
foreach ($areas as $area => $classes) {
    if ($area === 'Event') {
        continue;
    }
    $out .= sprintf("\n### %s\n\n| Name | Kind | What it is |\n| --- | --- | --- |\n", $area);
    foreach ($classes as $name) {
        $class = new ReflectionClass($name);
        $out .= sprintf("| `%s` | %s | %s |\n", $class->getShortName(), $kind($class), $cell($summary($class->getDocComment())));
    }
}

echo $out;
